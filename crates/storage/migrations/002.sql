BEGIN IMMEDIATE;
CREATE TABLE IF NOT EXISTS entries(id TEXT PRIMARY KEY NOT NULL,request_key TEXT UNIQUE NOT NULL,payload TEXT NOT NULL,bytes BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS snapshots(id TEXT PRIMARY KEY NOT NULL, repo_id TEXT NOT NULL, worktree_id TEXT NOT NULL, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS events(seq INTEGER PRIMARY KEY AUTOINCREMENT, id TEXT UNIQUE NOT NULL, repo_id TEXT NOT NULL, worktree_id TEXT NOT NULL, request_key TEXT NOT NULL, fingerprint TEXT NOT NULL, receipt TEXT NOT NULL, summary TEXT NOT NULL, data TEXT NOT NULL, UNIQUE(repo_id,worktree_id,request_key));
CREATE INDEX IF NOT EXISTS events_scope ON events(repo_id,worktree_id,seq);
CREATE TABLE IF NOT EXISTS comparisons(id TEXT PRIMARY KEY NOT NULL, data TEXT NOT NULL);
CREATE VIRTUAL TABLE IF NOT EXISTS event_search USING fts5(id UNINDEXED,repo_id UNINDEXED,summary);
PRAGMA user_version=2;
COMMIT;
